print(f"\nTraining History:")
for i, (tl, vl, vs) in enumerate(zip(training_history['train_loss'],
                                       training_history['val_loss'],
                                       training_history['val_smape'])):
    print(f"  Epoch {i+1}: Train Loss={tl:.4f}, Val Loss={vl:.4f}, Val SMAPE={vs:.2f}%")

print(f"\nModel saved at: {config.model_save_path}/")
print(f"Files saved:")
print(f"  - best_model.pt (model weights and config)")
print(f"  - tokenizer files")
print(f"  - training_history.json")

print("\n✓ Ready for inference!")
